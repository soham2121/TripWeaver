-- Users, saved trips and collaboration (plan sections 8 and 12).
CREATE TABLE users (
    id UUID PRIMARY KEY,
    username VARCHAR(40) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(80),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- request_json: the planner input; result_json: the last plan. version: optimistic locking.
CREATE TABLE trips (
    id UUID PRIMARY KEY,
    owner_id UUID NOT NULL REFERENCES users (id),
    title VARCHAR(120) NOT NULL,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('ITINERARY', 'ROAD_TRIP')),
    request_json TEXT NOT NULL,
    result_json TEXT,
    version INTEGER NOT NULL,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_trips_owner ON trips (owner_id);

CREATE TABLE trip_members (
    trip_id UUID NOT NULL REFERENCES trips (id),
    user_id UUID NOT NULL REFERENCES users (id),
    role VARCHAR(10) NOT NULL CHECK (role IN ('EDITOR', 'VIEWER')),
    added_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (trip_id, user_id)
);
CREATE INDEX ix_trip_members_user ON trip_members (user_id);

-- Only the SHA-256 of the token is stored.
CREATE TABLE trip_share_links (
    id UUID PRIMARY KEY,
    trip_id UUID NOT NULL REFERENCES trips (id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_by UUID NOT NULL REFERENCES users (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE,
    revoked_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_trip_share_links_trip ON trip_share_links (trip_id);

CREATE TABLE activity_suggestions (
    id UUID PRIMARY KEY,
    trip_id UUID NOT NULL REFERENCES trips (id),
    place_id UUID NOT NULL REFERENCES places (id),
    day_number INTEGER,
    note VARCHAR(500),
    suggested_by UUID NOT NULL REFERENCES users (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_activity_suggestions_trip ON activity_suggestions (trip_id);

-- One vote per person per suggestion (duplicate-vote rule).
CREATE TABLE activity_votes (
    suggestion_id UUID NOT NULL REFERENCES activity_suggestions (id),
    user_id UUID NOT NULL REFERENCES users (id),
    vote SMALLINT NOT NULL CHECK (vote IN (-1, 1)),
    voted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (suggestion_id, user_id)
);

CREATE TABLE trip_expenses (
    id UUID PRIMARY KEY,
    trip_id UUID NOT NULL REFERENCES trips (id),
    paid_by UUID NOT NULL REFERENCES users (id),
    description VARCHAR(200) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_trip_expenses_trip ON trip_expenses (trip_id);

-- id gives a total order even when two changes share a timestamp.
CREATE TABLE trip_change_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id UUID NOT NULL REFERENCES trips (id),
    user_id UUID REFERENCES users (id),
    action VARCHAR(40) NOT NULL,
    summary VARCHAR(500) NOT NULL,
    version INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_trip_change_history_trip ON trip_change_history (trip_id, id);
